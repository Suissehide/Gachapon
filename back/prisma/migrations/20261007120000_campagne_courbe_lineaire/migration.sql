-- sur deux etages, le rythme d'un chapitre. Mesure : etages normaux 80-100 %
-- (cible 88 %), boss 67-74 % (cible 70 %). 1-1 inchange.
--
-- Le BUTIN n'est pas touche (`difficultyMult`, courbe independante).
--
-- Migration de DONNEES : le deploiement ne rejoue jamais le seed. Seuls
-- baseHp, baseAtk, baseDef, baseSpd et mitigationScale sont reecrits ;
-- attackPattern, appearance, element, level, palier et l'ordre des ennemis
