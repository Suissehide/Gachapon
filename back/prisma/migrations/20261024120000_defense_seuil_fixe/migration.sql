-- Défense à seuil fixe : la réduction de dégâts vaut DEF / (K + DEF) avec un
-- seuil K unique pour toutes les unités (GlobalConfig combat.defMitigationRef,
-- 100 -> 1000). La DEF a désormais un sens absolu : plus de DEF, c'est
-- toujours moins de dégâts subis, quelle que soit la carte.
--
-- 1. Ennemis (campagne, tour, raid). La clé mitigationScale disparaît. La DEF
--    ne suit plus l'échelle d'étage : DEF de base du barème x ENEMY_DEF_MULT
--    (10), ce qui conserve exactement la réduction de dégâts de chaque ennemi.
-- 2. Campagne et tour : PV et ATQ refittés au simulateur (scripts/tower-sim.ts,
--    modes campaign-fit et fit), cibles de victoire inchangées, butin non
--    touché. Apparence, élément, niveau, palier et ordre des ennemis sont
--    conservés ; attackPattern de tour réécrit comme le seed.
-- 3. Raid : seule la DEF du boss change (les PV de raid ne bougent pas, les
--    dégâts de l'équipe de référence varient de 1 %). Les raids ouverts
--    gardent leurs PV figés.
--
-- Migration de DONNÉES : le déploiement ne rejoue jamais le seed, et le
-- bootstrap de GlobalConfig est create-only. Valeurs absolues, garde sur
-- l'ancienne valeur de config : idempotent.

